(() => {
  const $ = (id) => document.getElementById(id);

  let generatedPayloadFormatter = "";
  let formatterHasBeenGenerated = false;

  const output = $("payloadFormatterOutput");
  if (output) {
    output.textContent = "";

    const observer = new MutationObserver(() => {
      if (!formatterHasBeenGenerated && output.textContent !== "") {
        output.textContent = "";
      }
    });

    observer.observe(output, { childList: true, characterData: true, subtree: true });
  }

  function has(id) {
    const element = $(id);
    return !!element && element.checked;
  }

  function pushCase(lines, enabled, caseLines) {
    if (enabled) {
      lines.push(...caseLines);
    }
  }

  function generatePayloadFormatter() {
    formatterHasBeenGenerated = true;
    const lines = [];

    lines.push("// TTN / The Things Stack uplink payload formatter.");
    lines.push("// Generated by tools/platformio-ini-generator.");
    lines.push("// Includes only the selected sensor fPorts plus common diagnostics.");
    lines.push("");
    lines.push("function bytesToString(bytes) {");
    lines.push("  return String.fromCharCode.apply(null, bytes);");
    lines.push("}");
    lines.push("");
    lines.push("function toNumber(value) {");
    lines.push("  const number = Number(value);");
    lines.push("  return Number.isFinite(number) ? number : null;");
    lines.push("}");
    lines.push("");
    lines.push("function parseCsvNumbers(decodedString) {");
    lines.push("  if (!decodedString || decodedString.length === 0) {");
    lines.push("    return [];");
    lines.push("  }");
    lines.push("");
    lines.push("  return decodedString.split(\",\").map(toNumber);");
    lines.push("}");
    lines.push("");
    lines.push("function numberOrDefault(value, fallback) {");
    lines.push("  return value === null || value === undefined ? fallback : value;");
    lines.push("}");
    lines.push("");
    lines.push("function makeInfoResult(input, decodedString) {");
    lines.push("  return {");
    lines.push("    data: {");
    lines.push("      f_port: input.fPort,");
    lines.push("      payload_raw: decodedString,");
    lines.push("      message: decodedString,");
    lines.push("      level: \"info\"");
    lines.push("    }");
    lines.push("  };");
    lines.push("}");
    lines.push("");
    lines.push("function makeWarningResult(input, decodedString) {");
    lines.push("  return {");
    lines.push("    data: {");
    lines.push("      f_port: input.fPort,");
    lines.push("      payload_raw: decodedString,");
    lines.push("      message: decodedString,");
    lines.push("      level: \"warning\"");
    lines.push("    },");
    lines.push("    warnings: [\"Warning: \" + decodedString]");
    lines.push("  };");
    lines.push("}");
    lines.push("");
    lines.push("function makeErrorResult(input, decodedString) {");
    lines.push("  return {");
    lines.push("    data: {");
    lines.push("      f_port: input.fPort,");
    lines.push("      payload_raw: decodedString,");
    lines.push("      message: decodedString,");
    lines.push("      level: \"error\"");
    lines.push("    },");
    lines.push("    errors: [\"Error: \" + decodedString]");
    lines.push("  };");
    lines.push("}");
    lines.push("");
    lines.push("function decodeUplink(input) {");
    lines.push("  const decodedString = bytesToString(input.bytes || []);");
    lines.push("  const variables = parseCsvNumbers(decodedString);");
    lines.push("");
    lines.push("  switch (input.fPort) {");

    pushCase(lines, has("hasGps"), [
      "    case 1: { // GPS location",
      "      const latitude = numberOrDefault(variables[0], 0);",
      "      const longitude = numberOrDefault(variables[1], 0);",
      "      const altitude = numberOrDefault(variables[2], 0);",
      "      const hdop = numberOrDefault(variables[3], 0);",
      "",
      "      return {",
      "        latitude: latitude,",
      "        longitude: longitude,",
      "        altitude: altitude,",
      "        hdop: hdop,",
      "        data: {",
      "          f_port: input.fPort,",
      "          payload_raw: decodedString,",
      "          latitude: latitude,",
      "          longitude: longitude,",
      "          altitude: altitude,",
      "          hdop: hdop",
      "        }",
      "      };",
      "    }",
      ""
    ]);

    pushCase(lines, has("hasTemperature"), [
      "    case 2: { // DS18B20 temperature",
      "      return {",
      "        data: {",
      "          f_port: input.fPort,",
      "          payload_raw: decodedString,",
      "          temperature_c: numberOrDefault(variables[0], 0)",
      "        }",
      "      };",
      "    }",
      ""
    ]);

    pushCase(lines, has("hasPh"), [
      "    case 3: { // PH4502C pH level",
      "      return {",
      "        data: {",
      "          f_port: input.fPort,",
      "          payload_raw: decodedString,",
      "          ph_level: numberOrDefault(variables[0], 0)",
      "        }",
      "      };",
      "    }",
      ""
    ]);

    pushCase(lines, has("hasTds"), [
      "    case 4: { // Gravity TDS ppm + compensation temperature",
      "      return {",
      "        data: {",
      "          f_port: input.fPort,",
      "          payload_raw: decodedString,",
      "          tds_ppm: numberOrDefault(variables[0], 0),",
      "          temperature_c: numberOrDefault(variables[1], 0)",
      "        }",
      "      };",
      "    }",
      ""
    ]);

    pushCase(lines, has("hasTurbidity"), [
      "    case 5: { // Turbidity NTU",
      "      return {",
      "        data: {",
      "          f_port: input.fPort,",
      "          payload_raw: decodedString,",
      "          turbidity_ntu: numberOrDefault(variables[0], 0)",
      "        }",
      "      };",
      "    }",
      ""
    ]);

    lines.push("    case 220:");
    lines.push("      return {");
    lines.push("        data: {");
    lines.push("          f_port: input.fPort,");
    lines.push("          payload_raw: decodedString,");
    lines.push("          message: \"Request further downlinks\"");
    lines.push("        }");
    lines.push("      };");
    lines.push("");
    lines.push("    case 221:");
    lines.push("      return makeInfoResult(input, decodedString);");
    lines.push("");
    lines.push("    case 222:");
    lines.push("      return makeWarningResult(input, decodedString);");
    lines.push("");
    lines.push("    case 223:");
    lines.push("      return makeErrorResult(input, decodedString);");
    lines.push("");
    lines.push("    default:");
    lines.push("      return {");
    lines.push("        data: {");
    lines.push("          f_port: input.fPort,");
    lines.push("          payload_raw: decodedString,");
    lines.push("          message: decodedString,");
    lines.push("          level: \"error\"");
    lines.push("        },");
    lines.push("        errors: [\"Error (fatal): fPort \" + input.fPort + \" in uplink not enabled by this formatter\"]");
    lines.push("      };");
    lines.push("  }");
    lines.push("}");

    generatedPayloadFormatter = lines.join("\n") + "\n";

    const output = $("payloadFormatterOutput");
    if (output) {
      output.textContent = generatedPayloadFormatter;
    }

    const copyButton = $("copyFormatterButton");
    const downloadButton = $("downloadFormatterButton");
    if (copyButton) {
      copyButton.disabled = false;
    }
    if (downloadButton) {
      downloadButton.disabled = false;
    }
  }

  function downloadText(filename, content) {
    const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
    const link = document.createElement("a");
    link.href = URL.createObjectURL(blob);
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(link.href);
  }

  async function copyPayloadFormatter(event) {
    event?.stopImmediatePropagation();

    if (!generatedPayloadFormatter) {
      return;
    }

    await navigator.clipboard.writeText(generatedPayloadFormatter);

    const button = $("copyFormatterButton");
    if (button) {
      const previousText = button.textContent;
      button.textContent = "Copied";
      setTimeout(() => {
        button.textContent = previousText;
      }, 1200);
    }
  }

  function downloadPayloadFormatter(event) {
    event?.stopImmediatePropagation();

    if (!generatedPayloadFormatter) {
      return;
    }

    downloadText("payload-formatter.js", generatedPayloadFormatter);
  }

  $("generateFormatterButton")?.addEventListener("click", generatePayloadFormatter, true);
  $("copyFormatterButton")?.addEventListener("click", copyPayloadFormatter, true);
  $("downloadFormatterButton")?.addEventListener("click", downloadPayloadFormatter, true);
})();
